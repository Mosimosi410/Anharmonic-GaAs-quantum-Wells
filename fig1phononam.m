%% ========================================================================
% ELR - Acoustic Phonon (DP)
% Polar Coordinate Version
% GaAs
%% ========================================================================

clear; clc; close all;

%% ========================================================================
% CONSTANTS
%% ========================================================================

e       = 1.602176634e-19;
hbar    = 1.054571817e-34;
m0      = 9.10938356e-31;
kB      = 1.380649e-23;
epsilon0= 8.854e-12;

meV = e/1000;

%% ========================================================================
% MATERIAL : GaAs
%% ========================================================================

m_eff = 0.067*m0;

rho   = 5310;              % kg/m^3
vs    = 5220;              % m/s
Dac   = 12.42*e;           % J

chi0  = 13.18;

ne    = 3e22;              % m^-3
EF    = 25*meV;

%% ========================================================================
% SYSTEM
%% ========================================================================

B   = 5;

Lx  = 10e-9;
Ly  = 10e-9;
Lz  = 10e-9;

U0  = 250*meV;

Te  = 77;
Tp  =4.2;

E0  = 1.1e4;
a0  = 7.5e-9;

ellmax = 1;

%% ========================================================================
% QUANTUM NUMBERS
%% ========================================================================

N1 = 0;
n1 = 0;

N2 = 1;
n2 = 0;

%% ========================================================================
% FREQUENCIES
%% ========================================================================

omega_c = e*B/m_eff;

omega_z = sqrt(8*U0/(m_eff*Lz^2));

lB = sqrt(hbar/(m_eff*omega_c));
lz = sqrt(hbar/(m_eff*omega_z));

%% ========================================================================
% ENERGY SPECTRUM
%% ========================================================================

Ei = (N1+0.5)*hbar*omega_c ...
   + (n1+0.5)*hbar*omega_z;

Ef = (N2+0.5)*hbar*omega_c ...
   + (n2+0.5)*hbar*omega_z;

DeltaE = Ef - Ei;

fprintf('\n');
fprintf('DeltaE = %.4f meV\n',DeltaE/meV);

%% ========================================================================
% FERMI FACTOR
%% ========================================================================

fi = 1/(exp((Ei-EF)/(kB*Te))+1);
ff = 1/(exp((Ef-EF)/(kB*Te))+1);

FermiFactor = fi*(1-ff);

%% ========================================================================
% ELECTRON NUMBER
%% ========================================================================

Ne = ne*Lx*Ly*Lz;

%% ========================================================================
% WAVE FUNCTIONS
%% ========================================================================

alpha = (m_eff*U0)^(0.25)/sqrt(hbar*Lz);

psi_i = @(z) ...
sqrt(2*alpha/sqrt(pi)) ...
.*exp(-alpha.^2.*z.^2/2);

psi_f = @(z) ...
sqrt(alpha/sqrt(pi)) ...
.*exp(-alpha.^2.*z.^2/2) ...
.*(2*alpha.*z);

%% ========================================================================
% PHOTON ENERGY RANGE
%% ========================================================================

hOmega_draw = 5:0.05:25;

ELR = zeros(size(hOmega_draw));

%% ========================================================================
% q GRID
%% ========================================================================

qmax = 100/lB;
qmin = 1e-6/lB;

Nq  = 120;
Nth = 80;

qVec  = linspace(qmin,qmax,Nq);
thVec = linspace(0,pi,Nth);

[Q,TH] = meshgrid(qVec,thVec);

%% ========================================================================
% FORM FACTOR THETA
%% ========================================================================

disp('Calculating Theta(qz)...');

ThetaGrid = zeros(size(Q));

for k = 1:numel(Q)

    q  = Q(k);
    th = TH(k);

    qz = q*cos(th);

    Mz = integral( ...
        @(z) psi_i(z) ...
        .*exp(1i*qz.*z) ...
        .*psi_f(z), ...
        -Lz/2,Lz/2);

    ThetaGrid(k) = abs(Mz).^2;

end

%% ========================================================================
% FORM FACTOR XI
%% ========================================================================

qperp = Q.*sin(TH);

u = hbar*qperp.^2/(2*m_eff*omega_c);

XiGrid = exp(-u).*u;

fprintf('max ThetaGrid = %.4e\n',max(ThetaGrid(:)));
fprintf('max XiGrid    = %.4e\n',max(XiGrid(:)));

%% ========================================================================
% CONSTANT PREFATOR
%% ========================================================================

C0 = (Lx^2*Ly^2*Dac^2) ...
    /(16*pi^3*lB^4*Ne*rho*vs);

C0 = C0*FermiFactor;

%% ========================================================================
% MAIN LOOP
%% ========================================================================

Gamma = 1*meV;

for idx = 1:length(hOmega_draw)

    hOmega = hOmega_draw(idx)*meV;

    Omega = hOmega/hbar;

    TotalRate = 0;

    for ell = 1:ellmax

        %% ------------------------------------------------------------
        % Multi-photon factor
        %% ------------------------------------------------------------

        EMWa = a0^(2*ell-2) ...
             /(2^(ell-1)*(factorial(ell)^2)*lB^(2*ell-2));

        %% ------------------------------------------------------------
        % Acoustic phonon
        %% ------------------------------------------------------------

        PhononEnergy = hbar*vs*Q;

        %% ------------------------------------------------------------
        % Bose distribution
        %% ------------------------------------------------------------

        NqBose = 1./(exp(PhononEnergy./(kB*Tp))-1);

        %% ------------------------------------------------------------
        % Thermal factor
        %% ------------------------------------------------------------

        Thermal = exp( ...
            PhononEnergy.*(1/Tp-1/Te)./kB ) - 1;

        %% ------------------------------------------------------------
        % Lorentz broadening
        %% ------------------------------------------------------------

        DiracArg = DeltaE ...
                 + PhononEnergy ...
                 - ell*hOmega;

        DeltaLorentz = Gamma ...
            ./ (pi*(Gamma^2 + DiracArg.^2));

        %% ------------------------------------------------------------
        % Integrand
        %% ------------------------------------------------------------

        Integrand = ...
              ThetaGrid ...
            .* XiGrid ...
            .* (Q.^3) ...
            .* sin(TH) ...
            .* PhononEnergy ...
            .* NqBose ...
            .* Thermal ...
            .* DeltaLorentz;

        Integrand(~isfinite(Integrand)) = 0;

        %% ------------------------------------------------------------
        % Double integration
        %% ------------------------------------------------------------

        K = trapz(thVec,...
            trapz(qVec,Integrand,2));

        TotalRate = TotalRate ...
                  + EMWa*K/Omega^2;

    end

    ELR(idx) = C0*TotalRate;

    %% ------------------------------------------------------------
    % DEBUG
    %% ------------------------------------------------------------

    if mod(idx,100)==0

        fprintf('\n');
        fprintf('hOmega = %.2f meV\n',hOmega/meV);
        fprintf('K = %.4e\n',K);
        fprintf('max Lorentz = %.4e\n',max(DeltaLorentz(:)));

    end

end

%% ========================================================================
% PLOT
%% ========================================================================

figure;

plot(hOmega_draw,...
     ELR./1e-9,...
     'LineWidth',2);

grid on;

xlabel('$\hbar\Omega$ (meV)', ...
    'Interpreter','latex');

ylabel('ELR (nW/electron)');

title('GaAs Acoustic Phonon (DP)', ...
    'Interpreter','latex');